"""
ResNet18 + BiLSTM + Additive Attention Neural Network Architecture.

Designed for high-accuracy citizen grievance defect classification on resource-constrained
CPU environments (e.g. Render 512MB RAM free tier, Cloud Run CPU).

Architecture Pipeline:
1. Backbone: ResNet-18 feature extractor (layers conv1 through layer4, output shape: B x 512 x 7 x 7)
2. Spatial Flattener: Reshaped to spatial sequence (B x 49 x 512)
3. Sequence Encoder: Bidirectional LSTM (hidden_size=256, output shape: B x 49 x 512)
4. Context Aggregator: Additive (Bahdanau) Attention mechanism (weights shape: B x 49 x 1)
5. Classification Head: LayerNorm(512) -> Dropout(0.3) -> Linear(512 -> num_classes)
"""
from typing import Tuple, Optional
import torch
import torch.nn as nn
from torchvision import models


class AdditiveAttention(nn.Module):
    """
    Additive (Bahdanau) Attention mechanism.
    Learns spatial importance weights over the 49 feature tokens generated by ResNet18 + BiLSTM.
    """

    def __init__(self, hidden_dim: int = 512, attention_dim: int = 256) -> None:
        super().__init__()
        self.attention_layer = nn.Sequential(
            nn.Linear(hidden_dim, attention_dim),
            nn.Tanh(),
            nn.Linear(attention_dim, 1),
        )

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Args:
            x: Tensor of shape (batch_size, seq_len, hidden_dim)
        Returns:
            context: Aggregated context vector of shape (batch_size, hidden_dim)
            weights: Normalized attention weights of shape (batch_size, seq_len, 1)
        """
        scores = self.attention_layer(x)  # (batch_size, seq_len, 1)
        weights = torch.softmax(scores, dim=1)  # (batch_size, seq_len, 1)
        context = torch.sum(weights * x, dim=1)  # (batch_size, hidden_dim)
        return context, weights


class ResNet18BiLSTMAdditiveAttention(nn.Module):
    """
    Hybrid Deep Vision & Sequential Model combining:
    - ResNet-18 convolutional backbone
    - 1-layer Bidirectional LSTM
    - Additive Attention pooling
    - Regularized classification head (LayerNorm + Dropout + Linear)
    """

    def __init__(
        self,
        num_classes: int = 5,
        lstm_hidden_size: int = 256,
        dropout: float = 0.3,
    ) -> None:
        super().__init__()
        self.num_classes = num_classes
        self.lstm_hidden_size = lstm_hidden_size
        self.dropout_rate = dropout

        # 1. Convolutional Backbone (ResNet-18 without avgpool and fc)
        resnet = models.resnet18(weights=None)
        self.backbone = nn.Sequential(*list(resnet.children())[:8])

        # 2. Sequential Feature Extractor (BiLSTM)
        # Input: 512 channels from layer4. Output: 2 * 256 = 512 channels.
        self.bilstm = nn.LSTM(
            input_size=512,
            hidden_size=lstm_hidden_size,
            batch_first=True,
            bidirectional=True,
        )

        # 3. Additive Attention Pooling
        self.attention = AdditiveAttention(
            hidden_dim=lstm_hidden_size * 2,
            attention_dim=lstm_hidden_size,
        )

        # 4. Classification Head
        self.classifier = nn.Sequential(
            nn.LayerNorm(lstm_hidden_size * 2),
            nn.Dropout(dropout),
            nn.Linear(lstm_hidden_size * 2, num_classes),
        )

    def forward(
        self,
        x: torch.Tensor,
        return_attention_weights: bool = False,
    ) -> torch.Tensor | Tuple[torch.Tensor, torch.Tensor]:
        """
        Forward pass.
        Args:
            x: Input image batch of shape (batch_size, 3, 224, 224)
            return_attention_weights: If True, also return attention weights tensor
        Returns:
            logits: Class logits of shape (batch_size, num_classes)
            (optional) weights: Attention weights of shape (batch_size, 49, 1)
        """
        # Backbone feature extraction: (B, 3, 224, 224) -> (B, 512, 7, 7)
        features = self.backbone(x)

        # Reshape spatial grid to sequence of tokens: (B, 512, 7, 7) -> (B, 49, 512)
        seq = features.flatten(2).permute(0, 2, 1)

        # BiLSTM encoding: (B, 49, 512) -> (B, 49, 512)
        lstm_out, _ = self.bilstm(seq)

        # Attention pooling: (B, 49, 512) -> (B, 512)
        context, attn_weights = self.attention(lstm_out)

        # Classification logits: (B, 512) -> (B, num_classes)
        logits = self.classifier(context)

        if return_attention_weights:
            return logits, attn_weights
        return logits
